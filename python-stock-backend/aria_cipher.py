_C1 = 0x517CC1B727220A94FE13ABE8FA9A6EE0
_C2 = 0x6DB14ACC9E21C820FF28B1D5EF5DE2B0
_C3 = 0xDB92371D2126E9700324977504E8C90E
_MASK128 = (1 << 128) - 1

# Diffusion layer A (16x16 involutory binary matrix): output byte i is the XOR of
# the listed input bytes.
_A_ROWS = (
    (3, 4, 6, 8, 9, 13, 14), (2, 5, 7, 8, 9, 12, 15), (1, 4, 6, 10, 11, 12, 15), (0, 5, 7, 10, 11, 13, 14),
    (0, 2, 5, 8, 11, 14, 15), (1, 3, 4, 9, 10, 14, 15), (0, 2, 7, 9, 10, 12, 13), (1, 3, 6, 8, 11, 12, 13),
    (0, 1, 4, 7, 10, 13, 15), (0, 1, 5, 6, 11, 12, 14), (2, 3, 5, 6, 8, 13, 15), (2, 3, 4, 7, 9, 12, 14),
    (1, 2, 6, 7, 9, 11, 12), (0, 3, 6, 7, 8, 10, 13), (0, 3, 4, 5, 9, 11, 14), (1, 2, 4, 5, 8, 10, 15),
)
_SL1 = (SB1, SB2, SB3, SB4) * 4
_SL2 = (SB3, SB4, SB1, SB2) * 4


def _diffuse(x: bytes) -> bytes:
    out = bytearray(16)
    for i, row in enumerate(_A_ROWS):
        v = 0
        for j in row:
            v ^= x[j]
        out[i] = v
    return bytes(out)


def _sub(x: bytes, boxes) -> bytes:
    return bytes(boxes[i][x[i]] for i in range(16))


def _xor(a: bytes, b: bytes) -> bytes:
    return bytes(i ^ j for i, j in zip(a, b))


def _fo(d: bytes, rk: bytes) -> bytes:  # odd round function
    return _diffuse(_sub(_xor(d, rk), _SL1))


def _fe(d: bytes, rk: bytes) -> bytes:  # even round function
    return _diffuse(_sub(_xor(d, rk), _SL2))


def _rotr(v: int, n: int) -> int:
    return ((v >> n) | (v << (128 - n))) & _MASK128


def _i2b(v: int) -> bytes:
    return v.to_bytes(16, "big")


def _b2i(b: bytes) -> int:
    return int.from_bytes(b, "big")


class ARIA:
    """ARIA block cipher. ``key`` must be 16, 24 or 32 bytes."""

    def __init__(self, key: bytes):
        if len(key) not in (16, 24, 32):
            raise ValueError("ARIA key must be 16, 24 or 32 bytes")
        self.key_bits = len(key) * 8
        self.rounds = {128: 12, 192: 14, 256: 16}[self.key_bits]
        self._ek = self._expand(key)
        self._dk = self._decrypt_keys(self._ek)

    # -- key schedule ----------------------------------------------------------
    def _expand(self, key: bytes) -> list[bytes]:
        padded = key + bytes(32 - len(key))
        kl, kr = padded[:16], padded[16:]
        ck = {128: (_C1, _C2, _C3), 192: (_C2, _C3, _C1), 256: (_C3, _C1, _C2)}[self.key_bits]
        ck1, ck2, ck3 = (_i2b(c) for c in ck)
        w0 = kl
        w1 = _xor(_fo(w0, ck1), kr)
        w2 = _xor(_fe(w1, ck2), w0)
        w3 = _xor(_fo(w2, ck3), w1)
        w = [_b2i(x) for x in (w0, w1, w2, w3)]
        keys = []
        for shift in (19, 31, 128 - 61, 128 - 31, 128 - 19):  # >>>19, >>>31, <<<61, <<<31, <<<19
            for i in range(4):
                keys.append(_i2b(w[i] ^ _rotr(w[(i + 1) % 4], shift)))
                if len(keys) == 17:
                    break
        return keys[: self.rounds + 1]

    def _decrypt_keys(self, ek: list[bytes]) -> list[bytes]:
        n = self.rounds
        dk = [ek[n]]
        dk.extend(_diffuse(ek[i]) for i in range(n - 1, 0, -1))
        dk.append(ek[0])
        return dk

    # -- block operations ------------------------------------------------------
    def _crypt(self, block: bytes, rk: list[bytes]) -> bytes:
        if len(block) != 16:
            raise ValueError("ARIA block must be 16 bytes")
        d = block
        for r in range(self.rounds - 1):
            d = _fo(d, rk[r]) if r % 2 == 0 else _fe(d, rk[r])
        d = _sub(_xor(d, rk[self.rounds - 1]), _SL2)
        return _xor(d, rk[self.rounds])

    def encrypt_block(self, block: bytes) -> bytes:
        return self._crypt(block, self._ek)

    def decrypt_block(self, block: bytes) -> bytes:
        return self._crypt(block, self._dk)

    # -- CBC + PKCS#7 ----------------------------------------------------------
    def encrypt_cbc(self, data: bytes, iv: bytes) -> bytes:
        if len(iv) != 16:
            raise ValueError("IV must be 16 bytes")
        data = pkcs7_pad(data)
        out, prev = bytearray(), iv
        for i in range(0, len(data), 16):
            prev = self.encrypt_block(_xor(data[i : i + 16], prev))
            out += prev
        return bytes(out)

    def decrypt_cbc(self, data: bytes, iv: bytes) -> bytes:
        if len(iv) != 16 or len(data) % 16 or not data:
            raise ValueError("ciphertext must be a non-empty multiple of 16 bytes with a 16-byte IV")
        out, prev = bytearray(), iv
        for i in range(0, len(data), 16):
            block = data[i : i + 16]
            out += _xor(self.decrypt_block(block), prev)
            prev = block
        return pkcs7_unpad(bytes(out))


def pkcs7_pad(data: bytes) -> bytes:
    n = BLOCK_SIZE - len(data) % BLOCK_SIZE
    return data + bytes([n]) * n


def pkcs7_unpad(data: bytes) -> bytes:
    n = data[-1] if data else 0
    if not 1 <= n <= BLOCK_SIZE or data[-n:] != bytes([n]) * n:
        raise ValueError("잘못된 패딩입니다. 키 또는 암호문이 올바르지 않습니다.")
    return data[:-n]


# -- text helpers ---------------------------------------------------------------
def derive_key(passphrase: str, key_bits: int = 256) -> bytes:
    """Derive a fixed-length ARIA key from a passphrase (SHA-256, truncated).

    Demo helper only. In production keep the raw key in a secret store such as
    AWS Secrets Manager and pass it to ``ARIA`` directly.
    """
    if key_bits not in (128, 192, 256):
        raise ValueError("key_bits must be 128, 192 or 256")
    return hashlib.sha256(passphrase.encode("utf-8")).digest()[: key_bits // 8]


def encrypt_text(plaintext: str, key: bytes) -> str:
    iv = os.urandom(16)
    return base64.b64encode(iv + ARIA(key).encrypt_cbc(plaintext.encode("utf-8"), iv)).decode("ascii")


def decrypt_text(token: str, key: bytes) -> str:
    try:
        raw = base64.b64decode(token, validate=True)
    except Exception as exc:  # noqa: BLE001
        raise ValueError("암호문은 base64 문자열이어야 합니다.") from exc
    if len(raw) < 32:
        raise ValueError("암호문이 너무 짧습니다 (IV 16바이트 + 최소 1블록).")
    return ARIA(key).decrypt_cbc(raw[16:], raw[:16]).decode("utf-8")
